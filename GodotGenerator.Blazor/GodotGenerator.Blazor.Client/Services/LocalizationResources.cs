    /// <summary>
    /// Gets the localized text for a given key and culture.
    /// Falls back to English if the culture or key is not found.
    /// </summary>
    public static string GetText(string key, string cultureCode = "en")
    {
        if (string.IsNullOrWhiteSpace(key))
        {
            return key;
        }

        // Try to get the text for the specified culture
        if (Resources.TryGetValue(cultureCode, out var cultureResources) &&
            cultureResources.TryGetValue(key, out var text))
        {
            return text;
        }

        // Fallback to English
        if (Resources.TryGetValue("en", out var englishResources) &&
            englishResources.TryGetValue(key, out var englishText))
        {
            return englishText;
        }

        // Last resort: return the key itself
        return key;
    }

    /// <summary>
    /// Gets all available keys for localization.
    /// </summary>
    public static IEnumerable<string> GetAllKeys()
    {
        return Resources["en"].Keys.ToList();
    }
